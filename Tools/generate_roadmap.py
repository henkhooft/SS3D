#!/usr/bin/env python3
"""Generate ROADMAP.md and the README "Where the game is at" block from Documents/milestones/.

The gate docs are the source of truth. Each gate doc needs:
  - a `> Goal:` and a `> Roadmap: <Name> — <one-line player summary>` header line
  - a `## Slices` table with `Id`, `Status` and `Player view` columns

Gate order comes from the Gates table in Documents/milestones/INDEX.md. A slice's icon comes
from the first word of its Status cell: shipped, partial, pending or blocked. A slice whose
Player view starts with "Finish line:" is shown as the gate's finish line, not counted.

Usage:
  python3 Tools/generate_roadmap.py          # rewrite ROADMAP.md and the README block
  python3 Tools/generate_roadmap.py --check  # exit 1 if either is out of date
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MILESTONES = ROOT / "Documents" / "milestones"
ROADMAP = ROOT / "ROADMAP.md"
README = ROOT / "README.md"
README_START = "<!-- roadmap:start -->"
README_END = "<!-- roadmap:end -->"
FINISH = "Finish line:"

ICONS = {"shipped": "✅", "partial": "🟡", "pending": "⬜", "blocked": "⛔"}
ORDER = list(ICONS)
LEGEND = "✅ done · 🟡 partly there · ⬜ not started · ⛔ blocked"


class RoadmapError(Exception):
    pass


def table_rows(lines):
    """Yield each markdown table row in `lines` as a list of stripped cells."""
    for line in lines:
        if line.startswith("|"):
            yield [c.strip() for c in line.strip().strip("|").split("|")]


def section(text, heading):
    lines, inside = [], False
    for line in text.splitlines():
        if line.startswith("## "):
            inside = line.strip() == heading
            continue
        if inside:
            lines.append(line)
    return lines


def gate_files():
    text = (MILESTONES / "INDEX.md").read_text(encoding="utf-8")
    files = []
    for cells in table_rows(section(text, "## Gates")):
        m = re.search(r"\]\(([\w.-]+\.md)\)", cells[-1])
        if m:
            files.append(m.group(1))
    if not files:
        raise RoadmapError("no gate links found in the Gates table of Documents/milestones/INDEX.md")
    return files


def header(text, key, path):
    m = re.search(rf"^>\s*{key}:\s*(.+)$", text, re.MULTILINE)
    if not m:
        raise RoadmapError(f"{path}: missing `> {key}:` header line")
    return m.group(1).strip()


def parse_gate(filename):
    path = f"Documents/milestones/{filename}"
    text = (MILESTONES / filename).read_text(encoding="utf-8")
    name, _, summary = header(text, "Roadmap", path).partition(" — ")
    if not summary:
        raise RoadmapError(f"{path}: `> Roadmap:` must read `<Name> — <summary>`")
    rows = list(table_rows(section(text, "## Slices")))
    if not rows:
        raise RoadmapError(f"{path}: no `## Slices` table")
    head = rows[0]
    try:
        cid, cstatus, cview = head.index("Id"), head.index("Status"), head.index("Player view")
    except ValueError:
        raise RoadmapError(f"{path}: Slices table needs Id, Status and Player view columns") from None
    slices, finish = [], None
    for cells in rows[2:]:
        sid, view = cells[cid], cells[cview]
        word = re.match(r"\w+", cells[cstatus])
        status = word.group(0).lower() if word else ""
        if status not in ICONS:
            raise RoadmapError(f"{path}: slice {sid} status must start with one of {', '.join(ICONS)}")
        if not view:
            raise RoadmapError(f"{path}: slice {sid} has an empty Player view")
        if view.startswith(FINISH):
            finish = (sid, view[len(FINISH):].strip())
        else:
            slices.append((sid, status, view))
    return {
        "name": name.strip(),
        "summary": summary.strip(),
        "goal": header(text, "Goal", path),
        "file": filename,
        "slices": slices,
        "finish": finish,
    }


def anchor(title):
    return re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")


def progress(gate):
    statuses = [s for _, s, _ in gate["slices"]]
    text = f"{statuses.count('shipped')} of {len(statuses)} done"
    for word, label in (("partial", "partial"), ("blocked", "blocked")):
        if statuses.count(word):
            text += f", {statuses.count(word)} {label}"
    return text


def squares(gate):
    statuses = sorted((s for _, s, _ in gate["slices"]), key=ORDER.index)
    return "".join(ICONS[s] for s in statuses)


def render_roadmap(gates):
    out = [
        "<!-- Generated by Tools/generate_roadmap.py from Documents/milestones/. Do not edit by hand. -->",
        "",
        "# Roadmap",
        "",
        "Where the game is at, in plain language. This page is for players, testers and visitors.",
        "It is generated from the gate docs in [Documents/milestones/](Documents/milestones/INDEX.md),",
        "which contributors and agents work from.",
        "",
        f"**Legend:** {LEGEND}",
        "",
        "## The big picture",
        "",
        "The game is built towards a few **playable goals**: things a group of people can sit down and",
        "do end to end. Each goal is split into **slices**, the smaller pieces that have to work first.",
        "",
        "| Goal | What you'll be able to do | Progress |",
        "|------|---------------------------|----------|",
    ]
    for g in gates:
        out.append(f"| [{g['name']}](#{anchor(g['name'])}) | {g['summary']} | {progress(g)} |")
    out += [
        "",
        "What already works, system by system, is listed in",
        "[FORK_STATUS](Documents/FORK_STATUS.md#shipped-gameplay).",
    ]
    for g in gates:
        out += [
            "",
            f"## {g['name']}",
            "",
            f"**Goal:** {g['goal'].rstrip('.')}. [Details](Documents/milestones/{g['file']})",
            "",
            "| | Slice | What it means for a player |",
            "|---|---|---|",
        ]
        out += [f"| {ICONS[s]} | {sid} | {view} |" for sid, s, view in g["slices"]]
        if g["finish"]:
            sid, view = g["finish"]
            out += ["", f"**Finish line ({sid}):** {view.rstrip('.')}."]
    out += [
        "",
        "## Not on the roadmap yet",
        "",
        "Each goal's details page has an **Explicitly deferred** section listing what it leaves out on purpose.",
        "",
    ]
    return "\n".join(out)


def render_readme_block(gates):
    out = [
        README_START,
        "<!-- Generated by Tools/generate_roadmap.py. Do not edit by hand. -->",
        "### Where the game is at",
        "",
        "| Goal | Progress |",
        "|------|----------|",
    ]
    out += [f"| **{g['name']}**: {g['summary']} | {squares(g)} |" for g in gates]
    out += [
        "",
        f"Each square is one slice of the goal: {LEGEND}.",
        "**[Read the roadmap →](ROADMAP.md)**",
        README_END,
    ]
    return "\n".join(out)


def splice_readme(readme, block):
    start, end = readme.find(README_START), readme.find(README_END)
    if start < 0 or end < start:
        raise RoadmapError(f"README.md: missing {README_START} / {README_END} markers")
    return readme[:start] + block + readme[end + len(README_END):]


def main(argv):
    check = "--check" in argv
    try:
        gates = [parse_gate(f) for f in gate_files()]
        roadmap = render_roadmap(gates)
        readme_old = README.read_text(encoding="utf-8")
        readme = splice_readme(readme_old, render_readme_block(gates))
    except RoadmapError as e:
        print(f"generate_roadmap: {e}", file=sys.stderr)
        return 1
    roadmap_old = ROADMAP.read_text(encoding="utf-8") if ROADMAP.exists() else ""
    stale = [p.name for p, new, old in ((ROADMAP, roadmap, roadmap_old), (README, readme, readme_old)) if new != old]
    if check:
        if stale:
            print(f"generate_roadmap: out of date: {', '.join(stale)}. Run python3 Tools/generate_roadmap.py",
                  file=sys.stderr)
            return 1
        print("generate_roadmap: ROADMAP.md and README.md are up to date")
        return 0
    ROADMAP.write_text(roadmap, encoding="utf-8")
    README.write_text(readme, encoding="utf-8")
    print(f"generate_roadmap: wrote {', '.join(stale) or 'nothing (already up to date)'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
